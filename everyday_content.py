def _pick_tags(theme, rng):
    """テーマ固有タグを主にしつつ、汎用タグを1〜2個だけ混ぜて毎回少し変える。"""
    tags = list(theme["tags"])
    rng.shuffle(tags)
    tags = tags[: rng.randint(3, len(tags))] if len(tags) >= 3 else tags
    extra = rng.sample(GENERIC_TAGS, rng.randint(1, 2))
    for e in extra:
        if e not in tags:
            tags.append(e)
    return tags


def build_article(seed=None):
    """日常記事を1本組み立てて返す。

    Returns: dict(title, category, tags, body_html)
      body_html は画像・末尾リンクを含まない本文パラグラフのみ（<p>...</p> の連なり）。
    """
    rng = random.Random(seed)
    theme = rng.choice(THEMES)

    title = rng.choice(theme["titles"])
    intro = rng.choice(theme["intros"])
    body = rng.choice(theme["bodies"])
    close = rng.choice(theme["closes"])

    # 本題は常に2段落以上にする。30%で3段落。
    paragraphs = [intro, body]
    others = [b for b in theme["bodies"] if b != body]
    rng.shuffle(others)
    if others:
        paragraphs.append(others.pop())
    if others and rng.random() < 0.3:
        paragraphs.append(others.pop())
    paragraphs.append(close)

    # body には <br> 等の軽いHTMLを埋め込んでいるのでエスケープしない。
    body_html = "".join(f"<p>{p}</p>" for p in paragraphs)

    return {
        "title": title,
        "category": theme["category"],
        "tags": _pick_tags(theme, rng),
        "body_html": body_html,
    }


